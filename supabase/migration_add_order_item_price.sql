-- ============================================================
-- Миграция: цена товара на момент заказа (order_items.price)
-- Запустить ОДИН РАЗ в: Supabase → SQL Editor → New query → Run
--
-- Без этого сумма заказа всегда пересчитывается по ТЕКУЩЕЙ цене
-- в меню — если цену товара позже изменить, старые заказы
-- задним числом пересчитываются и у уже полностью оплаченных
-- заказов появляется "фантомный" долг на разницу.
--
-- После миграции цена фиксируется в момент создания/редактирования
-- заказа и больше не меняется при правках меню.
-- ============================================================

alter table order_items
  add column if not exists price numeric;

-- Бэкафилл существующих строк текущей ценой из меню — это лучшее
-- доступное приближение (историческую цену на момент заказа мы уже
-- не знаем). Останавливает дальнейшее "уплывание" сумм вперёд, но
-- уже возникшие расхождения по старым заказам это не отменяет —
-- их нужно закрыть вручную (см. историю платежей заказа).
update order_items oi
set price = mi.price
from menu_items mi
where oi.menu_item_id = mi.id
  and oi.price is null;
